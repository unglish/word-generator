import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { pathToFileURL } from "node:url";
import { benchmark, configuredBatchAPI } from "/Users/ryanbetts/.codex/worktrees/linguistic-q02-resumed/word-generator/evaluation/experiments/split-digraphs/performance-one-v2.mjs";
import { treePins, executionEnvironment } from "/Users/ryanbetts/.codex/worktrees/linguistic-q02-resumed/word-generator/evaluation/experiments/following-letter-conditions/freeze-capture.mjs";
import { installedDependencies } from "/Users/ryanbetts/.codex/worktrees/linguistic-q02-resumed/word-generator/evaluation/experiments/phoneme-aware-doubling/dependency-closure.mjs";
import { canonical } from "/Users/ryanbetts/.codex/worktrees/linguistic-q02-resumed/word-generator/evaluation/quality/serialization.ts";
const [arm, out] = process.argv.slice(2);
assert.equal(process.argv.length, 4);
assert(["spelling-stress-control", "final-word-provenance"].includes(arm));
assert.match(out, /^\/private\/tmp\/q02-performance-v1\/\d{2}-(control|candidate)\.json$/);
const root = arm === "spelling-stress-control" ? "/Users/ryanbetts/.codex/worktrees/linguistic-q02-control/word-generator" : "/Users/ryanbetts/.codex/worktrees/linguistic-q02-resumed/word-generator";
const sha = b => createHash("sha256").update(b).digest("hex");
const registrationBytes = await readFile("/Users/ryanbetts/.codex/worktrees/linguistic-q02-resumed/word-generator/evaluation/experiments/final-word-ownership/measurement.json");
const registration = JSON.parse(registrationBytes);
const freezeRoot = `/private/tmp/q02-${arm}-v1-freeze`;
const complete = JSON.parse(await readFile(`${freezeRoot}/complete.json`)); assert.equal(complete.passed, true);
const freeze = JSON.parse(await readFile(`${freezeRoot}/before.json`));
assert.equal(sha(registrationBytes), freeze.registration.registrationSha256);
const before = await treePins(`${root}/src`); assert.deepEqual(before, freeze.before.files.src);
assert.deepEqual(await installedDependencies(root), freeze.before.dependencies);
const environment = executionEnvironment();
const api = await import(pathToFileURL(`${root}/src/index.ts`).href);
const configuration = { ...api.englishConfig, splitVowels: registration.configuration.splitVowels, followingLetters: registration.configuration.followingLetters };
const result = benchmark(configuredBatchAPI(api, api.createGenerator(configuration)), undefined, process.env.CI === "true");
assert.deepEqual(await treePins(`${root}/src`), before);
assert.deepEqual(await installedDependencies(root), freeze.before.dependencies);
assert.deepEqual(executionEnvironment(), environment);
await writeFile(out, JSON.stringify({ arm, root, node: process.version, executableSha256: sha(await readFile(process.execPath)),
 environment, registrationSha256: sha(registrationBytes), configuration: canonical(configuration), source: before, ...result }, null, 2) + "\n", { flag: "wx" });
