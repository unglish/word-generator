import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
import {benchmark,configuredBatchAPI} from '/Users/ryanbetts/.codex/worktrees/linguistic-spelling/word-generator/evaluation/experiments/split-digraphs/performance-one-v2.mjs';
import {treePins,executionEnvironment} from '/Users/ryanbetts/.codex/worktrees/linguistic-spelling/word-generator/evaluation/experiments/following-letter-conditions/freeze-capture.mjs';
import {canonical} from '/Users/ryanbetts/.codex/worktrees/linguistic-spelling/word-generator/evaluation/quality/serialization.ts';
const candidate='/Users/ryanbetts/.codex/worktrees/linguistic-spelling/word-generator';
const parent='/private/tmp/q14b-parent-recovery-v1';
const [variant,out]=process.argv.slice(2);
assert.equal(process.argv.length,4);assert(['A','B'].includes(variant));
assert.match(out,/^\/private\/tmp\/q14b-performance-v1\/\d{2}-[AB]\.json$/);
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const registrationBytes=await readFile(candidate+'/evaluation/experiments/following-letter-conditions/measurement.json');
const registration=JSON.parse(registrationBytes);
const freeze=JSON.parse(await readFile('/private/tmp/q14b-following-letters-candidate-v1-freeze/before.json'));
assert.equal(sha(registrationBytes),freeze.registrationSha256);
const expected=variant==='B'?freeze.before.files.src:JSON.parse(await readFile(parent+'/evaluation/experiments/split-digraphs/evidence/capture/before.json')).before.files.src;
const root=variant==='B'?candidate:parent;
const before=await treePins(root+'/src');assert.deepEqual(before,expected);
const environment=executionEnvironment();
const api=await import(pathToFileURL(root+'/src/index.ts').href);
const configuration={...api.englishConfig,splitVowels:registration.splitVowels,...(variant==='B'?{followingLetters:registration.followingLetters}:{})};
assert.equal(configuration.followingLetters===undefined,variant==='A');
const generator=api.createGenerator(configuration);
const result=benchmark(configuredBatchAPI(api,generator),undefined,process.env.CI==='true');
assert.deepEqual(await treePins(root+'/src'),before);
assert.deepEqual(executionEnvironment(),environment);
await writeFile(out,JSON.stringify({variant,root,node:process.version,executableSha256:sha(await readFile(process.execPath)),environment,registrationSha256:sha(registrationBytes),configuration:canonical(configuration),source:before,...result},null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({variant,wordsPerSec:result.wordsPerSec,speedPass:result.speedPass,variancePass:result.variancePass}));
