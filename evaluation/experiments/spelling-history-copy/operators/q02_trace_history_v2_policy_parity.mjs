import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { once } from 'node:events';
import { createReadStream, createWriteStream } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { performance } from 'node:perf_hooks';
import { createInterface } from 'node:readline';
import { pathToFileURL } from 'node:url';
import { createGunzip, createGzip } from 'node:zlib';

const root = '/private/tmp/q02-trace-history-performance-v2';
const freeze = JSON.parse(await readFile(`${root}/source-freeze.json`, 'utf8'));
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
async function stable() {
  for (const [role, files] of Object.entries(freeze)) for (const file of files) {
    const bytes = await readFile(`${root}/${role}/${file.path}`);
    assert.equal(bytes.length, file.bytes);
    assert.equal(digest(bytes), file.sha256);
  }
}
await stable();
const api = await import(pathToFileURL(`${root}/candidate/src/index.ts`).href);
const generators = Object.fromEntries([['always', 100], ['never', 0]].map(([name, risingCodaDrop]) => [name, api.createGenerator({
  ...api.englishConfig,
  generationWeights: { ...api.englishConfig.generationWeights,
    boundaryPolicy: { ...api.englishConfig.generationWeights.boundaryPolicy, risingCodaDrop } },
})]));
const registration = JSON.parse(await readFile(`${root}/registration-with-capture.json`, 'utf8'));
assert.equal(digest(await readFile(registration.baselineCapture.path)), registration.baselineCapture.sha256);
const original = createInterface({ input: createReadStream(registration.baselineCapture.path).pipe(createGunzip()), crlfDelay: Infinity });
const file = createWriteStream(`${root}/candidate-policy-full-words.jsonl.gz`, { flags: 'wx' });
const gzip = createGzip({ level: 9 });
gzip.pipe(file);
const rawHash = createHash('sha256');
let words = 0;
const versions = {};
let generationMs = 0;
const counts = { always: 0, never: 0 };
for await (const line of original) {
  const recorded = JSON.parse(line);
  const seed = Math.floor(words / 2);
  const policy = words % 2 ? 'never' : 'always';
  assert.equal(recorded.seed, seed);
  assert.equal(recorded.policy, policy);
  assert(seed < 4000);
  const started = performance.now();
  const word = generators[policy].generateWord({ seed, mode: 'lexicon', morphology: false, trace: true, syllableCount: 4 });
  generationMs += performance.now() - started;
  const produced = JSON.stringify({ policy, seed, word });
  assert.equal(produced, line, `Full Word/trace byte difference at ${policy}/${seed}`);
  assert.equal(word.trace.baseSpelling.version, recorded.word.trace.baseSpelling.version);
  versions[word.trace.baseSpelling.version] = (versions[word.trace.baseSpelling.version] ?? 0) + 1;
  counts[policy] += word.trace.structural.filter(event => event.event === 'risingCodaBoundaryDrop').length;
  rawHash.update(`${produced}\n`);
  if (!gzip.write(`${produced}\n`)) await once(gzip, 'drain');
  words++;
  if (words % 1000 === 0) console.log(JSON.stringify({ words, generationMs, counts }));
}
gzip.end();
await once(file, 'finish');
await stable();
assert.equal(words, 8000);
assert.deepEqual(counts, { always: 5, never: 0 });
const baseline = registration.baselineCapture;
const rawWordsSha256 = rawHash.digest('hex');
assert.equal(rawWordsSha256, baseline.rawWordsSha256);
await writeFile(`${root}/candidate-policy-parity.json`, `${JSON.stringify({
  passed: true, completePublicWords: words, completeWordAndTraceBytesEqual: true,
  versions, counts, rawWordsSha256, generationMs,
  sourceFreezeSha256: digest(await readFile(`${root}/source-freeze.json`)),
  runnerSha256: digest(await readFile(new URL(import.meta.url))),
  scope: 'Every full original8000-word policy coordinate regenerated by candidate publicAPI and byte-compared to original baseline full Word/trace; allcomplete outputs retained. Timing here includes record I/O interaction and differs from baselineCPUprofile; no pairedspeed claim from these numbers.',
}, null, 2)}\n`, { flag: 'wx' });
console.log(JSON.stringify({ words, fullBytesEqual: true, counts, rawWordsSha256 }));
