import {readFileSync,writeFileSync} from "node:fs";
import {englishConfig} from "../../../src/index.ts";
import {BaseSpelling} from "../../../src/core/base-spelling.ts";
import {createCompletionPlanner} from "../../../src/core/spelling-completion-planner.ts";
import {prepareCompletionTransaction} from "../../../src/core/spelling-completion-transaction.ts";
const trace=JSON.parse(readFileSync(new URL("first-stream-divergence.json",import.meta.url))).controlWord.trace.baseSpelling;
if(trace.edits.length) throw Error("Reconstruction requires unedited source");
const splitVowels=JSON.parse(readFileSync(new URL("../completion-isolated-u/configuration.json",import.meta.url)));
const config={...englishConfig,splitVowels};
const planner=createCompletionPlanner(config,splitVowels.supports);
const base=new BaseSpelling(trace.phones,true,true,true);
for(const unit of trace.units) base.appendChoice(unit.choiceId,unit.selected,unit.afterDoubling,unit.inventoryIndex,unit.doublingIncrement);
base.setPhase("word");
const view=base.constructionState();
const attempt=planner.decide(view,1,[],()=>0.5);
const plan=prepareCompletionTransaction(view,planner,[],attempt,0,Math.max(...view.cells.map(c=>c.id))+1);
const result={scope:"Detached reconstruction of exact unedited retained source; not a public API corpus result",before:trace.surface,after:plan.cells.map(c=>c.text).join(""),attempt,certificate:plan.certificate};
writeFileSync(new URL("retained-case-check.json",import.meta.url),JSON.stringify(result,null,2)+"\n");
console.log(JSON.stringify({before:result.before,after:result.after}));
